#!/usr/bin/env python3
"""Install dev-brain into one or more coding agents.

usage: python3 install.py [opencode] [claude-code] [codex] [cursor]
       (no arguments: every agent whose CLI or config directory is found)

core/ is the only source. Each adapter below links it or translates its
frontmatter into what that agent reads; no rule lives in an adapter.
Idempotent: files that are not ours are moved to *.bak.<timestamp>, never deleted.
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

KIT = Path(__file__).resolve().parent
CORE = KIT / "core"
CONTEXT_SCRIPT = CORE / "bin" / "dev-brain-context"
BUILD = KIT / "build" / "marketplace"
MARKER = "generated by dev-brain install.py"
STAMP = time.strftime("%Y%m%d%H%M%S")
HOME = Path.home()
TOOLS = ("opencode", "claude-code", "codex", "cursor")


# ---------- source files ----------

def split_frontmatter(path):
    """(fields, body) of a Markdown file with simple `key: value` frontmatter."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}, text
    head, body = text[4:].split("\n---\n", 1)
    fields = {}
    for line in head.splitlines():
        if ":" in line and not line.startswith((" ", "#")):
            key, value = line.split(":", 1)
            fields[key.strip()] = value.strip()
    return fields, body.lstrip("\n")


def skills():
    return sorted(p for p in (CORE / "skills").iterdir() if (p / "SKILL.md").exists())


def workflows():
    return sorted(p for p in (CORE / "workflows").iterdir() if (p / "SKILL.md").exists())


def reviewer():
    return split_frontmatter(CORE / "agents" / "reviewer.md")


# ---------- safe file operations ----------

def owned(path):
    """True for our links (into this kit) and our generated files."""
    if path.is_symlink():
        return str(Path(os.readlink(path))).startswith(str(KIT))
    if path.is_file():
        try:
            return MARKER in path.read_text(encoding="utf-8", errors="ignore")[:400]
        except OSError:
            return False
    return False


def clear(path):
    if not (path.exists() or path.is_symlink()):
        return
    if owned(path):
        path.unlink()
    else:
        backup = path.with_name(f"{path.name}.bak.{STAMP}")
        path.rename(backup)
        print(f"  backed up: {path} -> {backup.name}")


def link(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.is_symlink() and Path(os.readlink(dst)) == src:
        return
    clear(dst)
    dst.symlink_to(src)


def write(dst, text):
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.is_file() and not dst.is_symlink() and dst.read_text(encoding="utf-8") == text:
        return
    clear(dst)
    dst.write_text(text, encoding="utf-8")


def update_json(path, change):
    """Apply change(dict) to a JSON file; leave it alone if it cannot be parsed."""
    data = {}
    if path.exists():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (ValueError, OSError) as error:
            print(f"  warning: cannot parse {path} ({error}); edit it by hand")
            return False
    change(data)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return True


def hook_command(fmt):
    return f'python3 "{CONTEXT_SCRIPT}" --format {fmt}'


def set_hook(data, event, entry, nested):
    """Replace our hook entry for `event` (found by script path), keep everyone else's."""
    hooks = data.setdefault("hooks", {})
    entries = [e for e in hooks.get(event, []) if "dev-brain-context" not in json.dumps(e)]
    hooks[event] = entries + [entry]
    if not nested:
        data.setdefault("version", 1)


def run(cmd):
    result = subprocess.run(cmd, capture_output=True, text=True)
    output = (result.stdout + result.stderr).strip().splitlines()
    print(f"  $ {' '.join(cmd)} -> {'ok' if result.returncode == 0 else 'exit ' + str(result.returncode)}"
          + (f" ({output[-1]})" if output and result.returncode else ""))
    return result.returncode == 0


def frontmatter(fields, comment=MARKER):
    lines = ["---", f"# {comment}"]
    for key, value in fields.items():
        lines.extend([f"{key}:"] + [f"  - {item}" for item in value] if isinstance(value, list) else [f"{key}: {value}"])
    return "\n".join(lines + ["---", ""]) + "\n"


# ---------- shared plugin bundle (Claude Code and Codex) ----------

def build_marketplace():
    """A local plugin marketplace with real copies: Codex copies plugins and drops symlinks."""
    plugin = BUILD / "dev-brain"
    shutil.rmtree(BUILD, ignore_errors=True)
    for source in skills() + workflows():
        shutil.copytree(source, plugin / "skills" / source.name)
    (plugin / "bin").mkdir(parents=True)
    shutil.copy2(CONTEXT_SCRIPT, plugin / "bin" / CONTEXT_SCRIPT.name)

    fields, body = reviewer()
    # Claude Code: only these tools; any other shell command needs the user's approval.
    tools = "Read, Grep, Glob, Bash(git diff:*), Bash(git log:*), Bash(git show:*), Bash(git status:*)"
    agent = frontmatter({"name": fields["name"], "description": fields["description"], "tools": tools}) + body
    (plugin / "agents").mkdir()
    (plugin / "agents" / "reviewer.md").write_text(agent, encoding="utf-8")

    hook = {"matcher": "startup|resume|clear|compact",
            "hooks": [{"type": "command", "command": 'python3 "${CLAUDE_PLUGIN_ROOT}/bin/dev-brain-context" --format hook'}]}
    (plugin / "hooks").mkdir()
    (plugin / "hooks" / "hooks.json").write_text(json.dumps({"hooks": {"SessionStart": [hook]}}, indent=2) + "\n")

    digest = hashlib.sha256()
    for path in sorted(plugin.rglob("*")):
        if path.is_file():
            digest.update(str(path.relative_to(plugin)).encode() + path.read_bytes())
    version = f"1.0.{int(digest.hexdigest()[:6], 16)}"  # changes with content, so agents refresh their copy
    manifest = {"name": "dev-brain", "version": version,
                "description": "Readable, maintainable code with low context cost: workflows, skills, read-only reviewer, saved state."}
    (plugin / ".claude-plugin").mkdir()
    (plugin / ".claude-plugin" / "plugin.json").write_text(json.dumps(manifest, indent=2) + "\n")
    market = {"name": "dev-brain", "owner": {"name": "dev-brain"},
              "plugins": [{"name": "dev-brain", "source": "./dev-brain", "description": manifest["description"]}]}
    (BUILD / ".claude-plugin").mkdir(parents=True)
    (BUILD / ".claude-plugin" / "marketplace.json").write_text(json.dumps(market, indent=2) + "\n")
    return BUILD


# ---------- adapters ----------

def install_opencode():
    config = Path(os.environ.get("XDG_CONFIG_HOME", HOME / ".config")) / "opencode"
    link(CORE / "AGENTS.md", config / "AGENTS.md")
    for source in skills():
        link(source, config / "skills" / source.name)
    for source in workflows():  # user-invoked: commands cost no context until used
        fields, body = split_frontmatter(source / "SKILL.md")
        write(config / "commands" / f"{source.name}.md",
              frontmatter({"description": fields["description"]}) + body.rstrip() + "\n\nUser input: $ARGUMENTS\n")
    fields, body = reviewer()
    # Last matching rule wins. Shell is read-only git; chained commands are split and each part
    # is checked, but redirection and --output are not, so they are denied explicitly.
    permissions = [
        '{ action: edit, resource: "*", effect: deny }',
        '{ action: shell, resource: "*", effect: deny }',
        '{ action: shell, resource: "git diff *", effect: allow }',
        '{ action: shell, resource: "git log *", effect: allow }',
        '{ action: shell, resource: "git show *", effect: allow }',
        '{ action: shell, resource: "git status *", effect: allow }',
        '{ action: shell, resource: "* --output*", effect: deny }',
        '{ action: shell, resource: "*>*", effect: deny }',
    ]
    write(config / "agents" / "reviewer.md",
          frontmatter({"description": fields["description"], "mode": "subagent", "permissions": permissions}) + body)

    plugin = str(KIT / "adapters" / "opencode" / "plugin")

    def register(data):
        data.setdefault("$schema", "https://opencode.ai/config.json")
        plugins = [p for p in data.setdefault("plugins", []) if not (isinstance(p, str) and p.endswith("/plugin/dev-brain"))]
        data["plugins"] = plugins + ([plugin] if plugin not in plugins else [])
    if not update_json(config / "opencode.json", register):
        print(f'  add manually: "plugins": ["{plugin}"]')
    return ["Restart the background server when no session is active: opencode service restart",
            "Workflows: /start /resume /handoff /plan /impact /learn /review"]


def install_claude_code():
    config = Path(os.environ.get("CLAUDE_CONFIG_DIR", HOME / ".claude"))
    memory = config / "CLAUDE.md"
    line = f"@{CORE / 'AGENTS.md'}"
    current = memory.read_text(encoding="utf-8") if memory.exists() else ""
    if line not in current:
        memory.parent.mkdir(parents=True, exist_ok=True)
        memory.write_text(current.rstrip("\n") + ("\n\n" if current.strip() else "") +
                          f"<!-- {MARKER}: global dev-brain rules -->\n{line}\n", encoding="utf-8")
    notes = ["Workflows: /dev-brain:review (or /review when the name is free), same for the others"]
    if shutil.which("claude"):
        run(["claude", "plugin", "marketplace", "add", str(BUILD)])
        run(["claude", "plugin", "marketplace", "update", "dev-brain"])
        run(["claude", "plugin", "install", "dev-brain@dev-brain"])
    else:
        notes.insert(0, f"claude not on PATH: run `claude plugin marketplace add {BUILD}` and "
                        "`claude plugin install dev-brain@dev-brain`")
    return notes


def install_codex():
    home = Path(os.environ.get("CODEX_HOME", HOME / ".codex"))
    link(CORE / "AGENTS.md", home / "AGENTS.md")
    fields, body = reviewer()
    # The read-only sandbox is enforced by Codex itself, not by the prompt.
    # A TOML literal string keeps the body verbatim: no escape sequences.
    toml = (f"# {MARKER}\nname = {json.dumps(fields['name'])}\ndescription = {json.dumps(fields['description'])}\n"
            f"sandbox_mode = \"read-only\"\ndeveloper_instructions = '''\n{body.strip()}\n'''\n")
    write(home / "agents" / "reviewer.toml", toml)
    entry = {"matcher": "startup|resume|clear|compact", "hooks": [{"type": "command", "command": hook_command("hook")}]}
    update_json(home / "hooks.json", lambda data: set_hook(data, "SessionStart", entry, nested=True))
    notes = ["Approve the SessionStart hook once in the Codex TUI (new hooks need review before they run)",
             "Workflows are skills: $review, $resume, ... (or pick them from /skills)"]
    if shutil.which("codex"):
        run(["codex", "plugin", "marketplace", "add", str(BUILD)])
        run(["codex", "plugin", "add", "dev-brain@dev-brain"])
    else:
        notes.insert(0, f"codex not on PATH: run `codex plugin marketplace add {BUILD}` and `codex plugin add dev-brain@dev-brain`")
    return notes


def install_cursor():
    home = HOME / ".cursor"
    rules = (CORE / "AGENTS.md").read_text(encoding="utf-8")
    write(home / "rules" / "dev-brain.mdc",
          frontmatter({"description": "Personal engineering rules (dev-brain)", "alwaysApply": "true"}) + rules)
    for source in skills() + workflows():
        link(source, home / "skills" / source.name)
    fields, body = reviewer()
    write(home / "agents" / "reviewer.md",
          frontmatter({"name": fields["name"], "description": fields["description"], "readonly": "true"}) + body)
    update_json(home / "hooks.json", lambda data: set_hook(
        data, "sessionStart", {"command": hook_command("cursor")}, nested=False))
    return [f"If the agent ignores the rules, paste {CORE / 'AGENTS.md'} into Cursor Settings > Rules "
            "(file-based global rules are not always loaded)",
            "Workflows: /review, /resume, ... (skills invoked by name)"]


def detect():
    found = []
    if shutil.which("opencode"):
        found.append("opencode")
    if shutil.which("claude") or (HOME / ".claude").exists():
        found.append("claude-code")
    if shutil.which("codex") or (HOME / ".codex").exists():
        found.append("codex")
    if shutil.which("cursor") or shutil.which("cursor-agent") or (HOME / ".cursor").exists():
        found.append("cursor")
    return found


def main(argv):
    if any(arg in ("-h", "--help") for arg in argv):
        print(__doc__)
        return 0
    unknown = [arg for arg in argv if arg not in TOOLS]
    if unknown:
        print(f"unknown agent: {', '.join(unknown)} (choose from {', '.join(TOOLS)})")
        return 2
    chosen = argv or detect()
    if not chosen:
        print(f"No supported agent found. Name one: python3 install.py {' '.join(TOOLS)}")
        return 1
    if {"claude-code", "codex"} & set(chosen):
        build_marketplace()
    for tool in chosen:
        print(f"{tool}:")
        if tool == "opencode":
            notes = install_opencode()
        elif tool == "claude-code":
            notes = install_claude_code()
        elif tool == "codex":
            notes = install_codex()
        else:
            notes = install_cursor()
        for note in notes:
            print(f"  - {note}")
    print("Done. New sessions pick up the rules, workflows, skills and reviewer.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
